"""Compile approved, deliberately restricted SVG primitives into Flutter paths."""
from pathlib import Path
import hashlib,json,re,subprocess,xml.etree.ElementTree as ET
def require(condition, message):
 if not condition:
  raise ValueError(message)

root=Path(__file__).resolve().parents[1]
folder=root/'design/south-africa-2010/assets/r1'
manifest=json.loads((folder/'manifest.json').read_text())
require(manifest['approval']=='approved', 'Artwork manifest must be explicitly approved')
roles={'#111111':'ink','#FFC700':'yellow','#087F3E':'success','#0057B8':'primary','#C62828':'error'}
out=["// Generated by tool/generate_south_africa_artwork.py from approved R1 SVGs.","// Edit the approved masters through a reviewed revision, not these paths.","import 'package:flutter/material.dart';", "import '../../theme/design_tokens.dart';"]
constants=[]
methods=[]
n=0
def number(x):
 v=float(x);require(abs(v)<1e6, f'Invalid artwork coordinate: {x}')
 return str(int(v)) if v.is_integer() else str(v)
def pathcode(d):
 tokens=re.findall(r'[A-Za-z]|[-+]?(?:\d*\.\d+|\d+)(?:[eE][-+]?\d+)?',d)
 sizes={'M':2,'L':2,'H':1,'V':1,'C':6,'Q':4,'Z':0}
 calls={'M':'moveTo','L':'lineTo','C':'cubicTo','Q':'quadraticBezierTo'}
 chunks=['Path()'];i=0;cmd=None;x=y=0;sx=sy=0
 while i<len(tokens):
  if tokens[i].isalpha():cmd=tokens[i];i+=1
  require(cmd in sizes, f'Unsupported path command: {cmd}')
  if cmd=='Z':chunks.append('..close()');x,y=sx,sy;cmd=None;continue
  count=sizes[cmd];a=list(map(float,tokens[i:i+count]));require(len(a)==count, f'Incomplete path command: {cmd}');i+=count
  if cmd=='H':x=a[0];chunks.append(f'..lineTo({number(x)}, {number(y)})')
  elif cmd=='V':y=a[0];chunks.append(f'..lineTo({number(x)}, {number(y)})')
  else:
   chunks.append('..'+calls[cmd]+'('+', '.join(number(v) for v in a)+')');x,y=a[-2:]
   if cmd=='M':sx,sy=x,y;cmd='L'
 return '\n    '.join(chunks)
def visit(e,style,lines):
 global n
 tag=e.tag.split('}')[-1]
 if tag=='title':return
 style=style|{k:v for k,v in e.attrib.items() if k in ['fill','stroke','stroke-width','stroke-linejoin']}
 transform=e.get('transform')
 if transform:
  match=re.fullmatch(r'translate\(([-\d.]+) ([-\d.]+)\)',transform);require(match is not None, f'Unsupported transform: {transform}')
  lines.extend(['canvas.save();',f'canvas.translate({match[1]}, {match[2]});'])
 if tag in ['path','circle']:
  n+=1;name=f'_path{n}'
  if tag=='path':code=pathcode(e.get('d'))
  else:code=f'Path()..addOval(Rect.fromCircle(center: const Offset({number(e.get("cx"))}, {number(e.get("cy"))}), radius: {number(e.get("r"))}))'
  constants.append(f'final {name} = {code};')
  for role,paintStyle in [('fill','fill'),('stroke','stroke')]:
   col=style.get(role, 'black' if role=='fill' else 'none')
   if col=='none':continue
   require(col in roles, f'Unsupported paint color: {col}')
   paint=f'Paint()..color = monochrome ?? AppColors.{roles[col]}..style = PaintingStyle.{paintStyle}'
   if role=='stroke':paint+=f'..strokeWidth = {number(style.get("stroke-width","1"))}..strokeJoin = StrokeJoin.round'
   lines.append(f'canvas.drawPath({name}, {paint});')
 elif tag not in ['svg','g']:raise ValueError(tag)
 for child in e:visit(child,style,lines)
 if transform:lines.append('canvas.restore();')
for asset in manifest['assets']:
 raw=(folder/asset['file']).read_bytes();require(hashlib.sha256(raw).hexdigest()==asset['sha256'], f'Artwork hash mismatch: {asset["file"]}')
 name=''.join(w.capitalize() for w in asset['id'].split('-'));lines=[];visit(ET.fromstring(raw),{},lines)
 methods.append(f'// {asset["id"]}: {asset["sha256"]}\nvoid draw{name}(Canvas canvas, Color? monochrome) {{\n  '+'\n  '.join(lines)+'\n}')
output_path=root/'lib/widgets/design/artwork_paths.dart'
output_path.write_text('\n\n'.join(out+constants+methods)+'\n')
subprocess.run(['dart', 'format', str(output_path)], check=True)
